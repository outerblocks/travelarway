function generateSeatMap(
  rows: number,
  columns: string[],
  busModel: string,
  busClass: string,
  registrationNumber: string,
  occupiedSeats: string[] = []
): BusSeatMap {
  const layout: BusSeat[][] = [];

  for (let row = 0; row < rows; row++) {
    const rowSeats: BusSeat[] = [];
    for (let col = 0; col < columns.length; col++) {
      const colChar = columns[col];
      const seatId = `${row + 1}${colChar}`;
      const isAisle = colChar === '_';
      const isDriver = row === 0 && (colChar === 'A' || colChar === 'B');

      if (isAisle) {
        rowSeats.push({
          id: `aisle_${row}_${col}`,
          row: row + 1,
          column: colChar,
          label: '',
          type: 'aisle',
          status: 'available',
        });
      } else if (isDriver) {
        rowSeats.push({
          id: `driver_${row}_${col}`,
          row: row + 1,
          column: colChar,
          label: '',
          type: 'driver',
          status: 'available',
        });
      } else {
        const isOccupied = occupiedSeats.includes(seatId);
        rowSeats.push({
          id: seatId,
          row: row + 1,
          column: colChar,
          label: seatId,
          type: 'seat',
          status: isOccupied ? 'occupied' : 'available',
        });
      }
    }
    layout.push(rowSeats);
  }

  return { rows, columns, layout, busModel, busClass, registrationNumber };
}

